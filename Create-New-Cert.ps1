function Compare-SemVer {
    # Returns -1 if A<B, 0 if equal, 1 if A>B. Non-semver (e.g. 'DEV') sorts as oldest (0.0.0),
    # so a 'DEV' build always treats a published version as newer. Prerelease suffix is ignored for ordering.
    param([string] $A, [string] $B)
    function ConvertTo-Ver([string] $v) {
        if ($v -match '^(\d+)\.(\d+)\.(\d+)') { return [version]("{0}.{1}.{2}" -f $Matches[1], $Matches[2], $Matches[3]) }
        return [version]'0.0.0'
    }
    $va = ConvertTo-Ver $A; $vb = ConvertTo-Ver $B
    if ($va -lt $vb) { return -1 } elseif ($va -gt $vb) { return 1 } else { return 0 }
}

function Invoke-WithRetry {
    param(
        [Parameter(Mandatory)][ScriptBlock] $ScriptBlock,
        [int] $MaxRetries = 3,
        [int] $InitialDelaySeconds = 3,
        [string] $OperationName = 'Operation'
    )
    $attempt = 1; $delay = $InitialDelaySeconds
    while ($true) {
        try { return & $ScriptBlock }
        catch {
            if ($attempt -ge $MaxRetries) { throw }
            Write-Log "$OperationName attempt $attempt failed: $($_.Exception.Message). Retrying in ${delay}s..." -Level WARNING
            Start-Sleep -Seconds $delay
            $delay *= 2; $attempt++
        }
    }
}

function Test-AuthenticodeAllowed {
    # The self-update gate: the running (trusted) script vets a downloaded .new before placing it.
    # On the fleet the signer chain is trusted (bootstrap installs codesign.cer) so Status is Valid; the
    # thumbprint allow-list is the real anchor.
    param([Parameter(Mandatory)][string] $FilePath)
    $sig = Get-AuthenticodeSignature -FilePath $FilePath
    if (-not $sig.SignerCertificate) { return @{ Allowed = $false; Reason = 'file is not signed' } }
    $thumb = $sig.SignerCertificate.Thumbprint
    if ($AllowedSignerThumbprints -notcontains $thumb) { return @{ Allowed = $false; Reason = "signer thumbprint $thumb not in allow-list" } }
    if ($sig.Status -ne 'Valid') { return @{ Allowed = $false; Reason = "signature status is $($sig.Status)" } }
    return @{ Allowed = $true; Reason = 'ok'; Thumbprint = $thumb }
}

function Get-ManifestContent {
    # The manifest exactly as published, as raw bytes: the detached signature is over these bytes, so the
    # manifest must never be parsed before it is verified (Invoke-RestMethod would parse it for us and lose
    # the bytes). Throws on any failure - the caller's Invoke-WithRetry handles that. SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Uri)
    $tmp = [IO.Path]::GetTempFileName()
    try {
        Invoke-WebRequest -Uri $Uri -OutFile $tmp -TimeoutSec 15 -UseBasicParsing | Out-Null
        return ,[IO.File]::ReadAllBytes($tmp)   # leading comma: hand back ONE byte[] rather than a stream of bytes
    }
    finally { [IO.File]::Delete($tmp) }
}

function Get-ManifestSignatureText {
    # The detached signature published beside the manifest (<manifest-url>.sig): base64 text. Returns $null
    # when the mirror has none (HTTP 404) - which Get-SignedManifest refuses under the shipped hard policy -
    # and throws on any other failure so the caller's retry sees it. SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Uri)
    try {
        $r = Invoke-WebRequest -Uri $Uri -TimeoutSec 15 -UseBasicParsing
        $text = if ($r.Content -is [byte[]]) { [Text.Encoding]::ASCII.GetString($r.Content) } else { [string]$r.Content }
        return $text.Trim()
    }
    catch {
        $code = $null
        try { $code = [int]$_.Exception.Response.StatusCode } catch { }
        if ($code -eq 404) { return $null }
        throw
    }
}

function Test-ManifestSignature {
    # Pure verification, never throws: ECDSA P-256 / SHA-256, signature in IEEE P1363 form (r||s, 64 bytes),
    # over the manifest bytes, against $AllowedManifestPublicKeys (SubjectPublicKeyInfo DER, base64). The key
    # is rebuilt from the SPKI's X/Y coordinates through ECParameters because that works on .NET Framework
    # 4.7+ (Windows PowerShell 5.1) AND .NET 8 (pwsh 7 on Linux); ImportSubjectPublicKeyInfo does not exist
    # on .NET Framework. Returns @{ Verified; Reason; KeyId } - or Unverifiable = $true when THIS runtime
    # lacks P-256 support, which the caller treats like a missing signature, not like a forged one.
    # SHARED VERBATIM.
    param([Parameter(Mandatory)][byte[]] $ManifestBytes, [Parameter(Mandatory)][string] $SignatureBase64)
    try { $sig = [Convert]::FromBase64String($SignatureBase64.Trim()) } catch { return @{ Verified = $false; Reason = 'signature is not valid base64' } }
    if ($sig.Length -ne 64) { return @{ Verified = $false; Reason = "signature is $($sig.Length) bytes, expected 64 (P-256 r||s)" } }
    $create = [System.Security.Cryptography.ECDsa].GetMethod('Create', [type[]]@([System.Security.Cryptography.ECParameters]))
    if (-not $create) { return @{ Verified = $false; Unverifiable = $true; Reason = 'this runtime cannot verify ECDSA P-256 (.NET Framework 4.7 or newer required)' } }
    # DER prefix of a P-256 SubjectPublicKeyInfo carrying an uncompressed point (26 header bytes + 0x04).
    $prefix = [byte[]](0x30,0x59,0x30,0x13,0x06,0x07,0x2a,0x86,0x48,0xce,0x3d,0x02,0x01,0x06,0x08,0x2a,0x86,0x48,0xce,0x3d,0x03,0x01,0x07,0x03,0x42,0x00,0x04)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        foreach ($keyB64 in @($AllowedManifestPublicKeys)) {
            try {
                $spki = [Convert]::FromBase64String([string]$keyB64)
                if ($spki.Length -ne 91) { continue }
                $isP256 = $true
                for ($i = 0; $i -lt $prefix.Length; $i++) { if ($spki[$i] -ne $prefix[$i]) { $isP256 = $false; break } }
                if (-not $isP256) { continue }
                $x = New-Object byte[] 32; $y = New-Object byte[] 32
                [Array]::Copy($spki, 27, $x, 0, 32); [Array]::Copy($spki, 59, $y, 0, 32)
                $q = New-Object System.Security.Cryptography.ECPoint; $q.X = $x; $q.Y = $y
                $p = New-Object System.Security.Cryptography.ECParameters
                $p.Curve = [System.Security.Cryptography.ECCurve+NamedCurves]::nistP256; $p.Q = $q
                $ecdsa = [System.Security.Cryptography.ECDsa]::Create($p)
                try {
                    if ($ecdsa.VerifyData($ManifestBytes, $sig, [System.Security.Cryptography.HashAlgorithmName]::SHA256)) {
                        $keyId = ([BitConverter]::ToString($sha.ComputeHash($spki)) -replace '-', '').Substring(0, 16)
                        return @{ Verified = $true; Reason = 'ok'; KeyId = $keyId }
                    }
                }
                finally { $ecdsa.Dispose() }
            }
            catch { continue }   # a malformed allow-list entry must never turn into a throw
        }
    }
    finally { $sha.Dispose() }
    return @{ Verified = $false; Reason = 'signature does not verify against any allow-listed manifest key' }
}

function Get-SignedManifest {
    # Fetch manifest.json AND manifest.json.sig, verify, THEN parse. Returns
    #   @{ Status = 'Verified' | 'Missing' | 'Refused'; Manifest = <object, $null when Refused>; Reason; KeyId }
    # Policy (see $RequireManifestSignature - hard-coded, never configurable):
    #   present + valid                         -> Verified
    #   present + does NOT verify               -> Refused, ALWAYS - a wrong signature is evidence of
    #                                              tampering or a mis-signed release, never noise
    #   absent (404) / runtime cannot verify    -> HARD (the shipped policy): Refused. Soft, still
    #                                              implemented and tested but no longer shipped: WARNING +
    #                                              event ManifestSigMissing, Status 'Missing', manifest
    #                                              still returned
    # Callers turn Refused into their own refusal event + throw, exactly as they do for Authenticode.
    # Network failures throw (the caller's Invoke-WithRetry handles them). SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Uri)
    $bytes   = [byte[]](Get-ManifestContent -Uri $Uri)
    $sigText = Get-ManifestSignatureText -Uri "$Uri.sig"
    $status = 'Missing'; $reason = 'manifest.json.sig is not published'; $keyId = ''
    if (-not [string]::IsNullOrWhiteSpace($sigText)) {
        $v = Test-ManifestSignature -ManifestBytes $bytes -SignatureBase64 $sigText
        if ($v.Verified)          { $status = 'Verified'; $reason = 'ok'; $keyId = [string]$v.KeyId }
        elseif ($v.Unverifiable)  { $reason = [string]$v.Reason }
        else                      { return @{ Status = 'Refused'; Manifest = $null; Reason = [string]$v.Reason; KeyId = '' } }
    }
    if ($status -eq 'Verified') {
        Write-Log "Manifest signature verified (key $keyId)." -Level INFO
    }
    else {
        if ($RequireManifestSignature) { return @{ Status = 'Refused'; Manifest = $null; Reason = "$reason (a valid manifest signature is required)"; KeyId = '' } }
        Write-Log "Manifest signature not verified ($reason) - accepted under the soft rollout policy; Authenticode + SHA-256 still gate every download." -Level WARNING
        Write-EventLogEntry $EID.ManifestSigMissing Warning "Manifest signature not verified: $reason"
    }
    $json = [Text.Encoding]::UTF8.GetString($bytes)
    if ($json.Length -gt 0 -and $json[0] -eq [char]0xFEFF) { $json = $json.Substring(1) }
    return @{ Status = $status; Manifest = ($json | ConvertFrom-Json); Reason = $reason; KeyId = $keyId }
}

function New-ManifestSigEvent {
    # Telemetry canary for a manifest signature that did NOT verify (issue #97). Returns ONE work-event for
    # Send-Telemetry, or $null when the signature verified (or was never fetched) - so a healthy fleet adds no
    # rows at all, while a box that cannot verify reports one row per run. That is what the spec section 6.3
    # evidence gate needed: event ManifestSigMissing goes to the LOCAL event log only, so "zero of them across
    # the fleet" was not observable in Log Analytics, and SelfUpdateStatus could not tell a verified signature
    # apart from a missing one that was soft-accepted. It still earns its place now that the policy is hard:
    # SelfUpdateStatus says only 'Refused', while this row names the REASON and the manifest URL - and under
    # the hard policy every row is SignatureRefused, since nothing is soft-accepted any more. Uses EXISTING
    # telemetry columns only - no DCR /
    # ingestor / schema change. The manifest URL rides in Message because the gate is worded against the
    # PRODUCTION url (a lab run on a test channel must not read as fleet drift). Best-effort like every
    # telemetry path: this only builds an object - callers append it to the run's POST and never branch on
    # it, so it can never change the outcome of a run. SHARED VERBATIM.
    param(
        [object] $Signed,
        [Parameter(Mandatory)][string] $Component,
        [string] $Uri
    )
    if (-not $Signed -or ([string]$Signed.Status -eq 'Verified')) { return $null }
    $refused = ([string]$Signed.Status -eq 'Refused')
    [pscustomobject]@{
        Action        = 'manifest-unverified'
        RunOutcome    = $(if ($refused) { 'SignatureRefused' } else { 'SignatureMissing' })
        Severity      = $(if ($refused) { 'Error' } else { 'Warning' })
        Component     = $Component
        Message       = "$([string]$Signed.Reason) (manifest $Uri)"
        TimeGenerated = (Get-Date).ToUniversalTime().ToString('o')
    }
}

