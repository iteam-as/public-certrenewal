            LiveDir         = $null    # 'Files' deployment is Linux-only for now (D9)
        }
    }
    return [pscustomobject]@{
        ScriptsDir      = '/opt/certrenewal'
        ConfigDir       = '/etc/certrenewal'
        StateDir        = '/var/lib/certrenewal'
        Config          = '/etc/certrenewal/cert-config.json'
