function Write-Log {
    param(
        [Parameter(Mandatory)][string] $Message,
        [ValidateSet('INFO', 'SUCCESS', 'WARNING', 'ERROR', 'DEBUG')][string] $Level = 'INFO'
    )
    $line = "[{0}] [{1}] {2}" -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Level, $Message
    switch ($Level) {
        'SUCCESS' { Write-Host $line -ForegroundColor Green }
        'WARNING' { Write-Host $line -ForegroundColor Yellow }
        'ERROR'   { Write-Host $line -ForegroundColor Red }
        'DEBUG'   { Write-Host $line -ForegroundColor Gray }
        default   { Write-Host $line }
    }
}

function Write-EventLogEntry {
    param(
        [Parameter(Mandatory)][int] $EventId,
        [ValidateSet('Information', 'Warning', 'Error')][string] $EntryType = 'Information',
        [Parameter(Mandatory)][string] $Message
    )
    try {
        if (-not $IsWindowsHost) {
            # journald is the Linux event log. The -t tag keeps `journalctl -t CertRenewal` working as the
            # Get-WinEvent equivalent, and the [EID nnnn] prefix preserves the IDs dashboards key on - the
            # ranges are unchanged across platforms (renewal 1000-1050, creator 1100-1150, bootstrap
            # 1200-1250, App Proxy setup 1300-1350).
            $prio = switch ($EntryType) { 'Error' { 'err' } 'Warning' { 'warning' } default { 'info' } }
            Write-JournaldEntry -Tag $EventLogSource -Priority $prio -Message "[EID $EventId] $Message" `
                -EventId $EventId -Component $ScriptComponent
            return
        }
        if (-not [System.Diagnostics.EventLog]::SourceExists($EventLogSource)) {
            New-EventLog -LogName $EventLogName -Source $EventLogSource -ErrorAction Stop
        }
        Write-EventLog -LogName $EventLogName -Source $EventLogSource -EventId $EventId -EntryType $EntryType -Message $Message -ErrorAction Stop
    }
    catch {
        # Event Log needs admin to create the source; never fatal - transcript still captures everything.
        Write-Log "Event Log write skipped (id $EventId): $($_.Exception.Message)" -Level DEBUG
    }
}

function Test-NativeCommand {
    # Is this native binary actually present? Split into its own function for a testing reason worth
    # stating: a Pester stub or mock is a FUNCTION, so a `-CommandType Application` check can never see
    # it - which would leave every transport-selection branch below unreachable in tests anywhere but a
    # real Linux box. Mocking this one predicate instead keeps the production check strict (a PowerShell
    # function called `logger` must not be mistaken for the binary) while making the branches testable.
    # SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Name)
    return [bool](Get-Command $Name -CommandType Application -ErrorAction SilentlyContinue)
}

function Get-JournaldFieldBlock {
    # The journald native-protocol field block for one entry (spec section 8), built separately from the
    # sending for a concrete reason: a Pester mock does NOT receive piped input, so a block piped straight
    # into `logger --journald` is invisible to tests. Keeping the construction pure means the FIELDS are
    # asserted directly and the native call only has to be checked for having happened.
    # SHARED VERBATIM.
    param(
        [Parameter(Mandatory)][string] $Tag,
        [Parameter(Mandatory)][ValidateSet('info', 'warning', 'err')][string] $Priority,
        [Parameter(Mandatory)][string] $Message,
        [int] $EventId,
        [string] $Component
    )
    # PRIORITY is the NUMERIC syslog level in the native protocol, not the name systemd-cat takes.
    $syslogPriority = switch ($Priority) { 'err' { 3 } 'warning' { 4 } default { 6 } }
    $fields = @("MESSAGE=$Message", "PRIORITY=$syslogPriority", "SYSLOG_IDENTIFIER=$Tag")
    # Omitted rather than emitted empty, so a consumer can filter on presence.
    if ($EventId)   { $fields += "CERTRENEWAL_EID=$EventId" }
    if ($Component) { $fields += "CERTRENEWAL_SCRIPT=$Component" }
    return ($fields -join "`n")
}

function Test-LoggerJournaldSupport {
    # Does this box's logger understand --journald? util-linux/bsdutils does; a BusyBox logger does not.
    # Probed once and cached, because Write-JournaldEntry is called many times per run and shelling out to
    # `logger --help` each time would be absurd. SHARED VERBATIM.
    if ($null -ne $script:LoggerHasJournald) { return $script:LoggerHasJournald }
    $script:LoggerHasJournald = $false
    if (Test-NativeCommand 'logger') {
        try {
            $help = & logger --help 2>&1
            $script:LoggerHasJournald = [bool](@($help) -match '--journald')
        }
        catch { $script:LoggerHasJournald = $false }
    }
    return $script:LoggerHasJournald
}

function Write-JournaldEntry {
    # The Linux half of Write-EventLogEntry, split out so the native-command fallback lives in one place and
    # so tests can mock it. Three transports, best first:
    #
    #   logger --journald  writes NATIVE journald fields, so the event id becomes something you can QUERY
    #                      (`journalctl CERTRENEWAL_EID=1030`) instead of text every consumer has to parse
    #                      back out of a message. This is what spec section 8 asks for.
    #   systemd-cat        tag + priority only, no custom fields - the systemd baseline.
    #   logger -t          plain syslog, for a container with neither of the above.
    #
    # The `[EID nnnn]` message prefix is applied by the caller and therefore appears on ALL THREE, so
    # `journalctl -t CertRenewal` reads identically however the entry got in and nothing depends on which
    # transport a given box happened to have. The structured fields are a bonus on top, never the only
    # copy of the id. Throws if it cannot log at all - the caller treats that exactly like a failed Windows
    # event-log write (DEBUG line, run continues). SHARED VERBATIM.
    param(
        [Parameter(Mandatory)][string] $Tag,
        [Parameter(Mandatory)][ValidateSet('info', 'warning', 'err')][string] $Priority,
        [Parameter(Mandatory)][string] $Message,
        [int] $EventId,
        [string] $Component
    )
    # journald's native protocol needs a length-prefixed binary blob for any value containing a newline.
    # Folding to spaces keeps MESSAGE identical across all three transports and loses nothing that matters
    # in a one-line event entry (the transcript keeps the full text either way).
    $flat = ($Message -replace '\r?\n', ' ').Trim()

    if (Test-LoggerJournaldSupport) {
        Get-JournaldFieldBlock -Tag $Tag -Priority $Priority -Message $flat -EventId $EventId -Component $Component |
            & logger --journald
        if ($LASTEXITCODE -eq 0) { return }
    }
    if (Test-NativeCommand 'systemd-cat') {
        $flat | & systemd-cat -t $Tag -p $Priority
        if ($LASTEXITCODE -eq 0) { return }
    }
    if (Test-NativeCommand 'logger') {
        & logger -t $Tag -p "user.$Priority" -- $flat
        if ($LASTEXITCODE -eq 0) { return }
    }
    throw 'no journald or syslog transport could record the entry'
}

function Unprotect-Secret {
    # Read a stored secret value, whichever platform wrote it (issue #23 L1, D2). Windows: a base64
    # DPAPI-LocalMachine blob. Linux: the literal value behind a 'plain:' tag, in a 0600 root:root file.
    # Reading BOTH forms on both platforms is deliberate - a file that moves between platforms must not
    # break the run. Getting it REWRITTEN into the right at-rest form is Sync-SecretsFromVault's job, and
    # the two directions are not symmetric: a DPAPI blob is unreadable here on Linux, so returning $null
    # makes it count as changed for free, whereas a 'plain:' value on Windows reads back perfectly and
    # therefore needs an explicit tag check over there or it would never be re-protected. Never logs the
    # value. SHARED VERBATIM.
    param([string] $Stored)
    if ([string]::IsNullOrWhiteSpace($Stored)) { return $null }
    if ($Stored.StartsWith('plain:')) { return $Stored.Substring(6) }   # ':' is not in the base64 alphabet
    if (-not $IsWindowsHost) { return $null }
    return Unprotect-Dpapi -Base64Blob $Stored
}

function Protect-Secret {
    # Store a secret value for this platform (the inverse of Unprotect-Secret). Windows encrypts with
    # DPAPI-LocalMachine; Linux tags the plain value, because against the only threat that matters here -
    # someone with root on the box - DPAPI and mode 0600 are equally worthless, the unattended run has to be
    # able to read it either way, and the product owner ruled a TPM disproportionate for these four values
    # (2026-09-08). The vault stays the source of truth, so a leak is recovered by rotating there and letting
    # the daily sync push it out. Empty in -> $null out, matching Protect-Dpapi. SHARED VERBATIM.
    param([string] $PlainText)
    if ([string]::IsNullOrEmpty($PlainText)) { return $null }
    if (-not $IsWindowsHost) { return "plain:$PlainText" }
    return Protect-Dpapi -PlainText $PlainText
}

function Set-RestrictedFileAccess {
    # Lock a secrets file down to the identity the unattended run uses: Administrators + SYSTEM on Windows
    # (SIDs, not names, for locale independence), 0600 root:root on Linux. chmod/chown rather than
    # [IO.File]::SetUnixFileMode: .NET has no ownership API at all, so chown is needed whichever way the mode
    # is set, and one mechanism for both beats two. Never fatal on either platform - a failure is logged and
    # the run continues, as it always has.
    # SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Path)
    try {
        if (-not $IsWindowsHost) {
            & chmod 0600 -- $Path
            if ($LASTEXITCODE -ne 0) { throw "chmod 0600 exited $LASTEXITCODE" }
            # chown only does anything as root, which the systemd unit always is. A non-root context (a test,
            # an operator poking at it) legitimately cannot chown, and 0600 has already done the real work.
            & chown root:root -- $Path 2>$null
            if ($LASTEXITCODE -ne 0) { Write-Log "  chown root:root skipped on ${Path} (not root)." -Level DEBUG }
            else { Write-Log "  Restricted $Path to 0600 root:root." -Level DEBUG }
            return
        }
        $adminSid  = New-Object System.Security.Principal.SecurityIdentifier('S-1-5-32-544')   # BUILTIN\Administrators
        $systemSid = New-Object System.Security.Principal.SecurityIdentifier('S-1-5-18')        # NT AUTHORITY\SYSTEM
        $acl = New-Object System.Security.AccessControl.FileSecurity
        $acl.SetAccessRuleProtection($true, $false)   # protect from inheritance, drop inherited rules
        foreach ($sid in $adminSid, $systemSid) {
            $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule(
                $sid, 'FullControl', 'Allow')))
        }
        $acl.SetOwner($adminSid)
        Set-Acl -Path $Path -AclObject $acl
        Write-Log "  Restricted ACL on cert-secrets.json (Administrators + SYSTEM only)." -Level DEBUG
    }
    catch { Write-Log "Could not restrict access on ${Path}: $($_.Exception.Message)" -Level WARNING }
}

function Set-FileOwnerAndMode {
    # Apply ownership and a mode to a file on Linux. The generalised sibling of Set-RestrictedFileAccess
    # (which is the fixed 0600 root:root case for secrets): 'Files' deployment needs a CONFIGURABLE mode and
    # owner so a service account can read the key without a hook. No-op on Windows, where the 'Files' type
    # inherits the directory ACL and Owner/Group/Mode are meaningless. chmod/chown binaries rather than
    # [IO.File]::SetUnixFileMode, for the same reason: there is no ownership API, and this one needs both.
    # Never fatal - a mode that could not be applied is a WARNING, because the certificate itself is
    # already correctly on disk. SHARED VERBATIM.
    param(
        [Parameter(Mandatory)][string] $Path,
        [string] $Owner = 'root',
        [string] $Group = 'root',
        [string] $Mode  = '0640'
    )
    if ($IsWindowsHost) { return }
    try {
        & chmod $Mode -- $Path
        if ($LASTEXITCODE -ne 0) { throw "chmod $Mode exited $LASTEXITCODE" }
        & chown "${Owner}:${Group}" -- $Path 2>$null
        if ($LASTEXITCODE -ne 0) { Write-Log "  chown ${Owner}:${Group} skipped on ${Path} (not root)." -Level DEBUG }
    }
    catch { Write-Log "Could not apply ${Mode} ${Owner}:${Group} to ${Path}: $($_.Exception.Message)" -Level WARNING }
}

function Unprotect-Dpapi {
    # Decrypt a base64 DPAPI-LocalMachine blob (as written by bootstrap/creator) to a UTF-8 string.
    param([string] $Base64Blob)
    if ([string]::IsNullOrWhiteSpace($Base64Blob)) { return $null }
    $bytes = [Convert]::FromBase64String($Base64Blob)
    $clear = [System.Security.Cryptography.ProtectedData]::Unprotect(
        $bytes, $null, [System.Security.Cryptography.DataProtectionScope]::LocalMachine)
    return [System.Text.Encoding]::UTF8.GetString($clear)
}

function Protect-Dpapi {
    # Encrypt a UTF-8 string to a base64 DPAPI-LocalMachine blob (the inverse of Unprotect-Dpapi).
    param([string] $PlainText)
    # A [string] param coerces $null to '', so guard on empty (not $null) to stay the exact inverse of
    # Unprotect-Dpapi (empty/blank -> $null) - a null/empty in round-trips back to $null.
    if ([string]::IsNullOrEmpty($PlainText)) { return $null }
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($PlainText)
    $blob  = [System.Security.Cryptography.ProtectedData]::Protect(
        $bytes, $null, [System.Security.Cryptography.DataProtectionScope]::LocalMachine)
    return [Convert]::ToBase64String($blob)
}

function Get-CertConfig {
    if (-not (Test-Path $ConfigPath)) { throw "cert-config.json not found at $ConfigPath" }
    try { return Get-Content $ConfigPath -Raw | ConvertFrom-Json }
    catch { throw "cert-config.json is not valid JSON: $($_.Exception.Message)" }
}

function Invoke-WithRetry {
    param(
        [Parameter(Mandatory)][ScriptBlock] $ScriptBlock,
        [int] $MaxRetries = 3,
        [int] $InitialDelaySeconds = 3,
        [string] $OperationName = 'Operation'
    )
    $attempt = 1; $delay = $InitialDelaySeconds
    while ($true) {
        try { return & $ScriptBlock }
        catch {
            if ($attempt -ge $MaxRetries) { throw }
            Write-Log "$OperationName attempt $attempt failed: $($_.Exception.Message). Retrying in ${delay}s..." -Level WARNING
            Start-Sleep -Seconds $delay
            $delay *= 2; $attempt++
        }
    }
}

function Test-AuthenticodeAllowed {
    # The self-update gate: the running (trusted) script vets the downloaded .new before replacing itself.
    # On the fleet the signer chain is trusted (bootstrap installs codesign.cer) so Status is Valid; the
    # thumbprint allow-list is the real anchor.
    param([Parameter(Mandatory)][string] $FilePath)
    $sig = Get-AuthenticodeSignature -FilePath $FilePath
    if (-not $sig.SignerCertificate) { return @{ Allowed = $false; Reason = 'file is not signed' } }
    $thumb = $sig.SignerCertificate.Thumbprint
    if ($AllowedSignerThumbprints -notcontains $thumb) { return @{ Allowed = $false; Reason = "signer thumbprint $thumb not in allow-list" } }
    if ($sig.Status -ne 'Valid') { return @{ Allowed = $false; Reason = "signature status is $($sig.Status)" } }
    return @{ Allowed = $true; Reason = 'ok'; Thumbprint = $thumb }
}

function Get-ManifestContent {
    # The manifest exactly as published, as raw bytes: the detached signature is over these bytes, so the
    # manifest must never be parsed before it is verified (Invoke-RestMethod would parse it for us and lose
    # the bytes). Throws on any failure - the caller's Invoke-WithRetry handles that. SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Uri)
    $tmp = [IO.Path]::GetTempFileName()
    try {
        Invoke-WebRequest -Uri $Uri -OutFile $tmp -TimeoutSec 15 -UseBasicParsing | Out-Null
        return ,[IO.File]::ReadAllBytes($tmp)   # leading comma: hand back ONE byte[] rather than a stream of bytes
    }
    finally { [IO.File]::Delete($tmp) }
}

function Get-ManifestSignatureText {
    # The detached signature published beside the manifest (<manifest-url>.sig): base64 text. Returns $null
    # when the mirror has none (HTTP 404) - which Get-SignedManifest refuses under the shipped hard policy -
    # and throws on any other failure so the caller's retry sees it. SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Uri)
    try {
        $r = Invoke-WebRequest -Uri $Uri -TimeoutSec 15 -UseBasicParsing
        $text = if ($r.Content -is [byte[]]) { [Text.Encoding]::ASCII.GetString($r.Content) } else { [string]$r.Content }
        return $text.Trim()
    }
    catch {
        $code = $null
        try { $code = [int]$_.Exception.Response.StatusCode } catch { }
        if ($code -eq 404) { return $null }
        throw
    }
}

function Test-ManifestSignature {
    # Pure verification, never throws: ECDSA P-256 / SHA-256, signature in IEEE P1363 form (r||s, 64 bytes),
    # over the manifest bytes, against $AllowedManifestPublicKeys (SubjectPublicKeyInfo DER, base64). The key
    # is rebuilt from the SPKI's X/Y coordinates through ECParameters because that works on .NET Framework
    # 4.7+ (Windows PowerShell 5.1) AND .NET 8 (pwsh 7 on Linux); ImportSubjectPublicKeyInfo does not exist
    # on .NET Framework. Returns @{ Verified; Reason; KeyId } - or Unverifiable = $true when THIS runtime
    # lacks P-256 support, which the caller treats like a missing signature, not like a forged one.
    # SHARED VERBATIM.
    param([Parameter(Mandatory)][byte[]] $ManifestBytes, [Parameter(Mandatory)][string] $SignatureBase64)
    try { $sig = [Convert]::FromBase64String($SignatureBase64.Trim()) } catch { return @{ Verified = $false; Reason = 'signature is not valid base64' } }
    if ($sig.Length -ne 64) { return @{ Verified = $false; Reason = "signature is $($sig.Length) bytes, expected 64 (P-256 r||s)" } }
    $create = [System.Security.Cryptography.ECDsa].GetMethod('Create', [type[]]@([System.Security.Cryptography.ECParameters]))
    if (-not $create) { return @{ Verified = $false; Unverifiable = $true; Reason = 'this runtime cannot verify ECDSA P-256 (.NET Framework 4.7 or newer required)' } }
    # DER prefix of a P-256 SubjectPublicKeyInfo carrying an uncompressed point (26 header bytes + 0x04).
    $prefix = [byte[]](0x30,0x59,0x30,0x13,0x06,0x07,0x2a,0x86,0x48,0xce,0x3d,0x02,0x01,0x06,0x08,0x2a,0x86,0x48,0xce,0x3d,0x03,0x01,0x07,0x03,0x42,0x00,0x04)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        foreach ($keyB64 in @($AllowedManifestPublicKeys)) {
            try {
                $spki = [Convert]::FromBase64String([string]$keyB64)
                if ($spki.Length -ne 91) { continue }
                $isP256 = $true
                for ($i = 0; $i -lt $prefix.Length; $i++) { if ($spki[$i] -ne $prefix[$i]) { $isP256 = $false; break } }
                if (-not $isP256) { continue }
                $x = New-Object byte[] 32; $y = New-Object byte[] 32
                [Array]::Copy($spki, 27, $x, 0, 32); [Array]::Copy($spki, 59, $y, 0, 32)
                $q = New-Object System.Security.Cryptography.ECPoint; $q.X = $x; $q.Y = $y
                $p = New-Object System.Security.Cryptography.ECParameters
                $p.Curve = [System.Security.Cryptography.ECCurve+NamedCurves]::nistP256; $p.Q = $q
                $ecdsa = [System.Security.Cryptography.ECDsa]::Create($p)
                try {
                    if ($ecdsa.VerifyData($ManifestBytes, $sig, [System.Security.Cryptography.HashAlgorithmName]::SHA256)) {
                        $keyId = ([BitConverter]::ToString($sha.ComputeHash($spki)) -replace '-', '').Substring(0, 16)
                        return @{ Verified = $true; Reason = 'ok'; KeyId = $keyId }
                    }
                }
                finally { $ecdsa.Dispose() }
            }
            catch { continue }   # a malformed allow-list entry must never turn into a throw
        }
    }
    finally { $sha.Dispose() }
    return @{ Verified = $false; Reason = 'signature does not verify against any allow-listed manifest key' }
}

function Get-SignedManifest {
    # Fetch manifest.json AND manifest.json.sig, verify, THEN parse. Returns
    #   @{ Status = 'Verified' | 'Missing' | 'Refused'; Manifest = <object, $null when Refused>; Reason; KeyId }
    # Policy (see $RequireManifestSignature - hard-coded, never configurable):
    #   present + valid                         -> Verified
    #   present + does NOT verify               -> Refused, ALWAYS - a wrong signature is evidence of
    #                                              tampering or a mis-signed release, never noise
    #   absent (404) / runtime cannot verify    -> HARD (the shipped policy): Refused. Soft, still
    #                                              implemented and tested but no longer shipped: WARNING +
    #                                              event ManifestSigMissing, Status 'Missing', manifest
    #                                              still returned
    # Callers turn Refused into their own refusal event + throw, exactly as they do for Authenticode.
    # Network failures throw (the caller's Invoke-WithRetry handles them). SHARED VERBATIM.
    param([Parameter(Mandatory)][string] $Uri)
    $bytes   = [byte[]](Get-ManifestContent -Uri $Uri)
    $sigText = Get-ManifestSignatureText -Uri "$Uri.sig"
    $status = 'Missing'; $reason = 'manifest.json.sig is not published'; $keyId = ''
    if (-not [string]::IsNullOrWhiteSpace($sigText)) {
        $v = Test-ManifestSignature -ManifestBytes $bytes -SignatureBase64 $sigText
        if ($v.Verified)          { $status = 'Verified'; $reason = 'ok'; $keyId = [string]$v.KeyId }
        elseif ($v.Unverifiable)  { $reason = [string]$v.Reason }
        else                      { return @{ Status = 'Refused'; Manifest = $null; Reason = [string]$v.Reason; KeyId = '' } }
    }
    if ($status -eq 'Verified') {
        Write-Log "Manifest signature verified (key $keyId)." -Level INFO
    }
    else {
        if ($RequireManifestSignature) { return @{ Status = 'Refused'; Manifest = $null; Reason = "$reason (a valid manifest signature is required)"; KeyId = '' } }
        Write-Log "Manifest signature not verified ($reason) - accepted under the soft rollout policy; Authenticode + SHA-256 still gate every download." -Level WARNING
        Write-EventLogEntry $EID.ManifestSigMissing Warning "Manifest signature not verified: $reason"
    }
    $json = [Text.Encoding]::UTF8.GetString($bytes)
    if ($json.Length -gt 0 -and $json[0] -eq [char]0xFEFF) { $json = $json.Substring(1) }
    return @{ Status = $status; Manifest = ($json | ConvertFrom-Json); Reason = $reason; KeyId = $keyId }
}

function New-ManifestSigEvent {
    # Telemetry canary for a manifest signature that did NOT verify (issue #97). Returns ONE work-event for
    # Send-Telemetry, or $null when the signature verified (or was never fetched) - so a healthy fleet adds no
    # rows at all, while a box that cannot verify reports one row per run. That is what the spec section 6.3
    # evidence gate needed: event ManifestSigMissing goes to the LOCAL event log only, so "zero of them across
    # the fleet" was not observable in Log Analytics, and SelfUpdateStatus could not tell a verified signature
    # apart from a missing one that was soft-accepted. It still earns its place now that the policy is hard:
    # SelfUpdateStatus says only 'Refused', while this row names the REASON and the manifest URL - and under
    # the hard policy every row is SignatureRefused, since nothing is soft-accepted any more. Uses EXISTING
    # telemetry columns only - no DCR /
    # ingestor / schema change. The manifest URL rides in Message because the gate is worded against the
    # PRODUCTION url (a lab run on a test channel must not read as fleet drift). Best-effort like every
    # telemetry path: this only builds an object - callers append it to the run's POST and never branch on
    # it, so it can never change the outcome of a run. SHARED VERBATIM.
    param(
        [object] $Signed,
        [Parameter(Mandatory)][string] $Component,
        [string] $Uri
    )
    if (-not $Signed -or ([string]$Signed.Status -eq 'Verified')) { return $null }
    $refused = ([string]$Signed.Status -eq 'Refused')
    [pscustomobject]@{
        Action        = 'manifest-unverified'
        RunOutcome    = $(if ($refused) { 'SignatureRefused' } else { 'SignatureMissing' })
        Severity      = $(if ($refused) { 'Error' } else { 'Warning' })
        Component     = $Component
        Message       = "$([string]$Signed.Reason) (manifest $Uri)"
        TimeGenerated = (Get-Date).ToUniversalTime().ToString('o')
    }
}

