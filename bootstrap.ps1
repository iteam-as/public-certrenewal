function Resolve-GuideUrl {
    # Pick the operations-guide URL to show the operator: the manifest's docs.url when present AND under the
    # iteam-as GitHub prefixes, else the built-in mirror README ($DefaultGuideUrl). The manifest is fetched
    # over HTTPS and (since issue #23 L0) carries a detached signature that must now verify - but a signed
    # manifest is still only as trustworthy as whoever signed it, so its value must never be able to send an
    # admin's browser somewhere else; the prefix allow-list is hard-coded by design (never make it
    # configurable). Never throws.
    # SHARED VERBATIM by the creator + bootstrap (NOT renewal - it has no operator to show it to).
    param([object] $Manifest)
    $url = $DefaultGuideUrl
    try {
        $candidate = if ($Manifest -and $Manifest.docs) { [string]$Manifest.docs.url } else { $null }
        if ($candidate -and ($candidate -like 'https://github.com/iteam-as/*' -or $candidate -like 'https://raw.githubusercontent.com/iteam-as/*')) {
            $url = $candidate
        }
    }
    catch { }
    return $url
}

function Test-HostInteractive {
    # Is there actually a human on the other end of stdin?
    #
    # [Environment]::UserInteractive is NOT the answer on Linux: .NET hardcodes it to $true there, so
    # it stays $true under systemd, cron, Ansible, cloud-init, a container, or any plain
    # `sh install.sh < /dev/null`. Every prompt gate built on it alone was therefore dead on Linux,
    # and Read-Host went on to return $null at EOF - which surfaced as "You cannot call a method on a
    # null-valued expression", instead of the clear "supply -Abr/-InvoiceCode" message the
    # non-interactive branch exists to give.
    #
    # [Console]::IsInputRedirected is the portable half: $false only when stdin is a real terminal.
    # BOTH are needed - a Windows service reports UserInteractive $false with stdin not redirected,
    # and a Linux terminal reports UserInteractive $true with stdin not redirected. SHARED VERBATIM by
    # the creator + bootstrap; the renewal runs unattended and never prompts, so it has no copy.
    if (-not [Environment]::UserInteractive) { return $false }
    try { return (-not [Console]::IsInputRedirected) }
    catch { return $false }   # no console at all (a hosted runspace): treat as unattended
}

function Confirm-OperatorEmail {
    # Capture the accountable operator's work email for interactive, config-mutating runs (telemetry schema
    # v2 -> OperatorEmail). Required: re-prompts until a valid address is entered (no skip - that is the
    # point of accountability). Captured once per session: $script:OperatorEmail is reused on later calls.
    # Skips when already set, under -DryRun, or on a non-interactive host (unattended runs have no human, so
    # OperatorEmail stays null). Validates format only - the authenticated anchor is OperatorAccount (the OS
    # identity), since the logged-in account is often a shared/generic admin. SHARED VERBATIM by the creator
    # + bootstrap (NOT renewal - the renewal runs unattended and never calls this).
    if (-not [string]::IsNullOrWhiteSpace($script:OperatorEmail)) { return }
    if ($DryRun -or -not (Test-HostInteractive)) { return }
    Write-Log 'This run is recorded for audit. Enter your work email so the change is attributable.' -Level INFO
    while ($true) {
        $raw = Read-Host 'Your work email'
        # $null means the input stream ended (EOF). Nothing more is coming, so re-prompting would
        # spin forever; leave OperatorEmail unset and let the run continue unattributed.
        if ($null -eq $raw) { Write-Log 'No input available - continuing without an operator email.' -Level WARNING; return }
        $email = ([string]$raw).Trim()
        if ($email -match '^[^@\s]+@[^@\s]+\.[^@\s]+$') { $script:OperatorEmail = $email; return }
        Write-Log 'Enter a valid email address (e.g. name@firma.no).' -Level WARNING
    }
}

function Read-Billing {
    # Prompt for the per-install Billing block (plaintext customer identifiers, not secrets). Abr +
    # InvoiceCode are mandatory (re-prompt until given); CustomerName / CustomerNr / Services are optional.
    # Bootstrap-native (returns a Billing object, no save) because the creator's version calls creator-only
    # helpers. Set-BootstrapBilling gates when this is reached (interactive, no params, billing incomplete).
    Write-Log 'Enter the Billing block (customer identifiers stamped on Teams cards / telemetry):' -Level INFO
    $abr = ''
    while (-not $abr) { $abr = (Read-Host 'Abbreviation (Abr)').Trim(); if (-not $abr) { Write-Log 'Abbreviation (Abr) is required.' -Level WARNING } }
    $custName = (Read-Host 'Customer name').Trim()
    $custNr   = (Read-Host 'Customer number').Trim()
    $invoice  = ''
    while (-not $invoice) { $invoice = (Read-Host 'Invoice code').Trim(); if (-not $invoice) { Write-Log 'Invoice code is required.' -Level WARNING } }
    $svcRaw   = Read-Host 'Services (comma-separated) [CertRenewal]'
    $services = if ([string]::IsNullOrWhiteSpace($svcRaw)) { @('CertRenewal') }
                else { @($svcRaw -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) }
    return [pscustomobject][ordered]@{
        Abr = $abr; CustomerName = $custName; CustomerNr = $custNr; InvoiceCode = $invoice; Services = $services
    }
}

function Set-BootstrapBilling {
    # Force a complete Billing block onto a fresh/migrated box so telemetry/Teams are never stamped blank
    # (the gap: it otherwise stays null until someone runs the creator, which on an upgraded box may never
    # happen). Precedence: explicit -Abr/... params > an existing complete block > interactive prompt.
    # Unattended (non-interactive host) + incomplete + no params -> FATAL with a clear message (keeps the
    # no-hang unattended contract). DryRun -> log + skip. Returns the (possibly updated) config object.
    param([Parameter(Mandatory)][object] $Config)

    $b = $Config.Billing
    # Abr + InvoiceCode are the mandatory billing keys; CustomerName/CustomerNr/Services are optional.
    $complete    = $b -and $b.Abr -and $b.InvoiceCode
    $paramsGiven = $Abr -or $CustomerName -or $CustomerNr -or $InvoiceCode -or $Services

    if ($paramsGiven) {
        foreach ($pair in @{ '-Abr' = $Abr; '-InvoiceCode' = $InvoiceCode }.GetEnumerator()) {
            if ([string]::IsNullOrWhiteSpace($pair.Value)) { throw "Billing parameters are incomplete: $($pair.Key) is required (supply at least -Abr and -InvoiceCode)." }
        }
        $svc = if ($Services) { @($Services -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) } else { @('CertRenewal') }
        $billing = [pscustomobject][ordered]@{ Abr = $Abr; CustomerName = $CustomerName; CustomerNr = $CustomerNr; InvoiceCode = $InvoiceCode; Services = $svc }
        Write-Log "Billing block set from parameters (Customer: $CustomerName)." -Level INFO
    }
    elseif ($complete) {
        Write-Log "Billing block already present (Customer: $($b.CustomerName), Nr: $($b.CustomerNr), Invoice: $($b.InvoiceCode)); keeping it." -Level INFO
        return $Config
    }
    elseif ($DryRun) {
        Write-Log '[DryRun] WOULD prompt for the Billing block (no complete block present).' -Level INFO
        return $Config
    }
    elseif (-not (Test-HostInteractive)) {
        throw 'Billing block is missing and bootstrap is running non-interactively. Supply -Abr/-CustomerName/-CustomerNr/-InvoiceCode (and optional -Services), or run bootstrap in an interactive session.'
    }
    else {
        $billing = Read-Billing
    }

    $Config | Add-Member -NotePropertyName 'Billing' -NotePropertyValue $billing -Force
    $null = Save-CertConfig -Config $Config -Reason 'Billing block'
    return $Config
}

function Test-IsElevated {
    # True when this process can do the privileged work: LocalMachine cert stores, machine-wide modules,
    # the scheduled task / systemd units, and the event source. On Linux that is simply uid 0 - the systemd
    # unit runs as root and the whole /opt /etc /var layout is root-owned.
    if (-not $IsWindowsHost) { return ([int](& id -u) -eq 0) }
    $id = [System.Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object System.Security.Principal.WindowsPrincipal($id)
    return $principal.IsInRole([System.Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Initialize-InstallLayout {
    # Duty 0 - create the on-disk layout BEFORE anything writes into it (spec section2), and re-assert
    # its modes on every run.
    #
    # This must come first, and it must be FATAL, because nearly everything downstream is best-effort:
    # on a fresh Linux box a missing /etc/certrenewal makes Save-CertConfig log a WARNING and continue
    # "with in-memory configuration", makes the vault secrets sync log another - and then the scheduler
    # installs the timer anyway. The box reports a successful bootstrap and then fails every night with
    # no config to read. A pre-provisioned lab box cannot surface that; only a genuine first run can.
    #
    # Windows keeps everything under one C:\Cert\Renewal tree and inherits its ACL. Linux spreads over
    # four FHS trees whose MODES are part of the security story, so they are set explicitly - and
    # REAPPLIED every run, because a directory created once with the wrong mode stays wrong otherwise
    # (the lesson from the L1c 'Files' ownership bug, which only ever applied its mode at creation).
    param([Parameter(Mandatory)][object] $Layout)

    $dirs = @(
        [pscustomobject]@{ Path = $Layout.ScriptsDir; Mode = '0755'; What = 'signed scripts' }
        [pscustomobject]@{ Path = $Layout.LogDir;     Mode = '0750'; What = 'transcripts' }
    )
    if (-not $IsWindowsHost) {
        # spec section2: config 0750, keys 0700, state 0750. The keys directory holds the telemetry SP and
        # App Proxy PRIVATE keys, so it is closed to the group as well, as is the Posh-ACME home - that
        # directory holds the ACME account key and every issued certificate's key.
        $dirs += [pscustomobject]@{ Path = $Layout.ConfigDir;     Mode = '0750'; What = 'configuration' }
        $dirs += [pscustomobject]@{ Path = $Layout.KeyDir;        Mode = '0700'; What = 'machine credentials' }
        # 0751 (traverse, but do not list) on the two directories a SERVICE has to walk through. The
        # 'Files' Owner/Group recipe has a non-root service read its own key at
        # <LiveDir>/<domain>/privkey.pem, where the per-domain directory is 0750 root:<group> and the
        # key 0640 root:<group> - and that only works if every PARENT is traversable by that user.
        # Spec section2 said 0750 here; taking it literally broke the recipe outright (verified on a
        # real box: 0750 -> permission denied, 0751 -> reads fine). These two parents were never the
        # security boundary - the per-domain directory and the file modes are - so all they owe anyone
        # is passage. The execute-without-read bit still denies enumerating the deployed domains.
        # This is the L1c directory-traversal bug one level up, and 'reapply every run' would have
        # made it permanent rather than a one-off.
        $dirs += [pscustomobject]@{ Path = $Layout.StateDir;      Mode = '0751'; What = 'state' }
        $dirs += [pscustomobject]@{ Path = $Layout.ConfigBackups; Mode = '0750'; What = 'config backups' }
        $dirs += [pscustomobject]@{ Path = $Layout.PoshAcmeHome;  Mode = '0700'; What = 'Posh-ACME home (ACME account + cert keys)' }
        $dirs += [pscustomobject]@{ Path = $Layout.LiveDir;       Mode = '0751'; What = "'Files' deployment root" }
    }

    foreach ($d in $dirs) {
        if ([string]::IsNullOrWhiteSpace($d.Path)) { continue }   # KeyDir/LiveDir are $null on Windows
        $exists = Test-Path -LiteralPath $d.Path
        if ($DryRun) {
            # Windows has no mode to talk about (the ACL is inherited), so an existing directory there
            # means there is genuinely nothing this step would do.
            if ($IsWindowsHost) {
                if (-not $exists) { Write-Log "[DryRun] WOULD create $($d.Path) ($($d.What))." -Level INFO }
            }
            elseif ($exists) { Write-Log "[DryRun] WOULD re-assert mode $($d.Mode) root:root on $($d.Path) ($($d.What))." -Level INFO }
            else             { Write-Log "[DryRun] WOULD create $($d.Path) ($($d.What)), mode $($d.Mode) root:root." -Level INFO }
            continue
        }
        if (-not $exists) {
            # -ErrorAction Stop so the caller's try/catch turns this into a non-zero exit: a box that
            # cannot create /etc/certrenewal must NOT go on to schedule a renewal that can never run.
            New-Item -ItemType Directory -Path $d.Path -Force -ErrorAction Stop | Out-Null
            Write-Log "  Created $($d.Path) ($($d.What))." -Level INFO
        }
        # Best-effort by design (Set-FileOwnerAndMode warns rather than throws, and is a no-op on
        # Windows): the directory exists, which is what the run needs. A mode that could not be applied
        # is worth reporting, not worth aborting an otherwise good install over.
        Set-FileOwnerAndMode -Path $d.Path -Owner 'root' -Group 'root' -Mode $d.Mode
    }

    $where = if ($IsWindowsHost) { $Layout.ScriptsDir } else { '/etc/certrenewal, /opt/certrenewal, /var/lib/certrenewal, /var/log/certrenewal' }
    Write-Log "Filesystem layout ready ($where)." -Level SUCCESS
}

function Install-CodeSigningTrust {
    # Duty 1. Download codesign.cer, verify its thumbprint is in the pinned allow-list (NEVER install an
    # unpinned cert as a trust anchor), then import into LocalMachine\Root (chain validity) and
    # LocalMachine\TrustedPublisher (run under a restrictive policy). Idempotent per store. Must run
    # BEFORE any Save-VerifiedDownload (which requires Get-AuthenticodeSignature Status=Valid).
    param([string] $Url = $DefaultCodeSignCertUrl)
    # Windows-only: Authenticode, and the LocalMachine\Root / TrustedPublisher stores it needs, do not
    # exist on Linux. Integrity there rests on the SIGNED MANIFEST (issue #23 L0, verified BEFORE the
    # manifest is parsed) plus the per-file SHA-256 - two of the three gates a Windows box applies.
    # Said out loud rather than left implicit, because 'no Authenticode' reads like a weakening until
    # you can see what still holds.
    if (-not $IsWindowsHost) {
        Write-Log 'Skipping the code-signing trust import (Authenticode is Windows-only; the signed manifest + SHA-256 gate the downloads here).' -Level INFO
        return
    }
    $tmp = Join-Path $env:TEMP ("codesign-{0}.cer" -f ([guid]::NewGuid().ToString('N')))
    try {
        Write-Log "Downloading code-signing certificate from $Url" -Level INFO
        Invoke-WithRetry -OperationName 'codesign.cer download' -ScriptBlock {
            Invoke-WebRequest -Uri $Url -OutFile $tmp -TimeoutSec 30 -UseBasicParsing
        } | Out-Null
        $cert  = New-Object System.Security.Cryptography.X509Certificates.X509Certificate2 $tmp
        $thumb = $cert.Thumbprint
        if ($AllowedSignerThumbprints -notcontains $thumb) {
            throw "downloaded codesign.cer thumbprint $thumb is NOT in the allow-list - refusing to install it as a trust anchor."
        }
        Write-Log "Code-signing cert thumbprint $thumb verified against the allow-list." -Level SUCCESS
        if ($DryRun) {
            Write-Log '[DryRun] WOULD import codesign.cer into LocalMachine\Root and LocalMachine\TrustedPublisher.' -Level INFO
            return
        }
        foreach ($storeName in 'Root', 'TrustedPublisher') {
            $store = New-Object System.Security.Cryptography.X509Certificates.X509Store($storeName, 'LocalMachine')
            $store.Open('ReadWrite')
            try {
                if ($store.Certificates | Where-Object { $_.Thumbprint -eq $thumb }) {
                    Write-Log "  codesign.cer already present in LocalMachine\$storeName." -Level DEBUG
                }
                else {
                    $store.Add($cert)
                    Write-Log "  Installed codesign.cer into LocalMachine\$storeName." -Level SUCCESS
                }
            }
            finally { $store.Close() }
        }
        Write-EventLogEntry $EID.TrustInstalled Information "Code-signing trust installed ($thumb)"
    }
    finally { Remove-Item $tmp -Force -ErrorAction SilentlyContinue }
}

function Install-SpCert {
    # Duty 2 ("Fix B"). Import the telemetry/Key Vault SP cert non-exportable into LocalMachine\My, then
    # delete the supplied PFX from disk. Idempotent: skip if the thumbprint is already present. Fatal if
    # absent AND no PFX was supplied (the box can't do vault/telemetry auth without it).
    param([string] $PfxPath, [securestring] $Password)
    if (-not $IsWindowsHost) {
        # Linux has no machine certificate store, so there is nothing to import: the SP credential is a PEM
        # the operator places (D5, and the #79 gap - bootstrap cannot fetch it without already having it).
        # Missing it is a WARNING, not fatal (spec section 9): the box still renews certificates, it just
        # cannot reach the vault or send telemetry until the file is there. Print the exact commands rather
        # than a description of them, so this is copy-pasteable at 3am.
        $pem = (Get-PlatformPaths).KeyDir + '/telemetry-sp.pem'
        if (Test-Path -LiteralPath $pem) {
            Write-Log "SP cert PEM already present at $pem." -Level INFO
            return
        }
        Write-Log "No SP credential at $pem - vault sync and telemetry will be skipped until it exists." -Level WARNING
        Write-Log '  Place it from the telemetry-client.pfx (on a box that has it):' -Level INFO
        Write-Log "    openssl pkcs12 -in telemetry-client.pfx -nodes -clcerts -out $pem" -Level INFO
        Write-Log "    chmod 0600 $pem && chown root:root $pem" -Level INFO
        Write-Log '  -clcerts matters: the loader takes the FIRST certificate in the file, so a chain cert landing first would resolve the wrong identity.' -Level INFO
        return
    }
    $existing = Get-ChildItem Cert:\LocalMachine\My -ErrorAction SilentlyContinue |
        Where-Object { $_.Thumbprint -eq $TelemetrySpCertThumbprint } | Select-Object -First 1
    if ($existing) {
        Write-Log "SP cert $TelemetrySpCertThumbprint already present in LocalMachine\My (NotAfter $($existing.NotAfter)). Skipping import." -Level INFO
        return
    }
    if ([string]::IsNullOrWhiteSpace($PfxPath)) {
        throw "SP cert $TelemetrySpCertThumbprint is not in LocalMachine\My and no -TelemetryCertPfxPath was supplied. Supply telemetry-client.pfx (+ -TelemetryCertPassword) to bootstrap."
    }
    if (-not (Test-Path $PfxPath)) { throw "Telemetry SP-cert PFX not found at $PfxPath." }
    if ($DryRun) {
        Write-Log "[DryRun] WOULD import $PfxPath into LocalMachine\My (non-exportable) and delete the PFX." -Level INFO
        return
    }
    if (-not $Password) { throw "-TelemetryCertPassword is required to import $PfxPath." }
    $imported = Import-PfxCertificate -FilePath $PfxPath -CertStoreLocation Cert:\LocalMachine\My -Password $Password -Exportable:$false -ErrorAction Stop
    if ($imported.Thumbprint -ne $TelemetrySpCertThumbprint) {
        Write-Log "WARNING: imported PFX thumbprint $($imported.Thumbprint) != expected $TelemetrySpCertThumbprint. Continuing, but verify the correct PFX was supplied." -Level WARNING
    }
    Write-Log "Imported SP cert $($imported.Thumbprint) into LocalMachine\My (non-exportable)." -Level SUCCESS
    Write-EventLogEntry $EID.CertImported Information "Telemetry SP cert imported ($($imported.Thumbprint))"
    try {
        Remove-Item $PfxPath -Force -ErrorAction Stop
        Write-Log "Deleted the PFX from disk ($PfxPath)." -Level SUCCESS
    }
    catch { Write-Log "Could not delete the PFX at ${PfxPath}: $($_.Exception.Message). Delete it manually - it holds the private key." -Level WARNING }
}

function Install-RequiredModules {
    # Duty 3 ("Fix A", unattended). Ensure NuGet provider + PSGallery trust + TLS 1.2, then install the
    # modules the SYSTEM renewal + creator need, machine-wide (-Scope AllUsers) so the SYSTEM task can load
    # them. DnsClient-PS is creator-only (CAA walk in Test-CaaRecordForLetsEncrypt) but the creator hard-fails
    # without it, so it belongs in the baseline set. Born here; the creator's pending interactive "Fix A" copies this (sharing, not duplicating) and
    # wraps it with prompts. Best-effort per module: a failure warns + continues (Connect-SecretsVault /
    # Posh-ACME re-check at use; the box may still be partly usable).
    # Az is Windows-only for us now: the Linux Key Vault path is REST with a client-certificate assertion
    # (issue #23 L1c), precisely so a Linux box needs neither Az.Accounts nor Az.KeyVault - ~100MB of
    # modules and the Azure.Identity assembly-conflict failure mode, for two calls. Supersedes spec
    # section 9, which still listed them.
    param([string[]] $Modules = $(if ($IsWindowsHost) { @('Az.Accounts', 'Az.KeyVault', 'Posh-ACME', 'DnsClient-PS') }
                                  else               { @('Posh-ACME', 'DnsClient-PS') }))
    if ($DryRun) {
        Write-Log "[DryRun] WOULD ensure NuGet + PSGallery trust + install (AllUsers): $($Modules -join ', ')." -Level INFO
        return
    }
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        # The NuGet PACKAGE PROVIDER is a PowerShellGet-v2-on-Windows concern; pwsh on Linux ships a
        # PSGallery that needs no provider bootstrap, and Get-PackageProvider may not even be present.
        if ($IsWindowsHost -and -not (Get-PackageProvider -Name NuGet -ListAvailable -ErrorAction SilentlyContinue)) {
            Write-Log 'Installing NuGet package provider...' -Level INFO
            Install-PackageProvider -Name NuGet -MinimumVersion '2.8.5.201' -Force -Scope AllUsers | Out-Null
        }
        if ((Get-PSRepository -Name PSGallery -ErrorAction SilentlyContinue).InstallationPolicy -ne 'Trusted') {
            Set-PSRepository -Name PSGallery -InstallationPolicy Trusted -ErrorAction SilentlyContinue
        }
    }
    catch { Write-Log "Package provider / repository prep had a problem: $($_.Exception.Message). Continuing to module install." -Level WARNING }

    foreach ($m in $Modules) {
        try {
            if (Get-Module -ListAvailable -Name $m) {
                Write-Log "  Module '$m' already installed." -Level DEBUG
                continue
            }
            Write-Log "Installing module '$m' (AllUsers)..." -Level INFO
            Invoke-WithRetry -OperationName "Install-Module $m" -ScriptBlock {
                Install-Module -Name $m -Scope AllUsers -Force -AllowClobber -ErrorAction Stop
            } | Out-Null
            Write-Log "  Installed '$m'." -Level SUCCESS
        }
        catch { Write-Log "Failed to install module '${m}': $($_.Exception.Message). Continuing; the box may need a manual Install-Module." -Level WARNING }
    }
    Write-EventLogEntry $EID.ModulesInstalled Information "Required modules ensured: $($Modules -join ', ')"
}

function Install-FleetScripts {
    # Duty 4a. Download + verify (sha256 + Authenticode allow-list) the signed Renew-Cert.ps1 AND
    # Create-New-Cert.ps1 from the manifest. Renewal is REQUIRED (throws on failure -> fatal in Main); the
    # creator is best-effort (re-run bootstrap to retry). Requires the codesign trust (Duty 1) to be in
    # place first, else Save-VerifiedDownload's Authenticode gate refuses everything.
    $url = if ($ManifestUrl) { $ManifestUrl } else { $DefaultManifestUrl }
    Write-Log "Fetching manifest $url" -Level INFO
    $signed = Invoke-WithRetry -OperationName 'manifest fetch' -ScriptBlock { Get-SignedManifest -Uri $url }
    $script:ManifestSigEvent = New-ManifestSigEvent -Signed $signed -Component 'bootstrap' -Uri $url
    if ($signed.Status -eq 'Refused') {
        # Fatal by design: bootstrap must never place scripts from a manifest whose signature is present but
        # wrong (or, in hard mode, missing). Nothing has been installed at this point.
        Write-EventLogEntry $EID.SelfUpdate Error "Manifest signature refused: $($signed.Reason)"
        throw "manifest signature refused ($($signed.Reason)) - the manifest published at $url has no valid signature. Nothing was installed; contact the release owner."
    }
    $manifest = $signed.Manifest
    if (-not $manifest.renewal.version) { throw 'manifest has no renewal.version' }
    if (-not $manifest.creator.version) { throw 'manifest has no creator.version' }
    $script:GuideUrl = Resolve-GuideUrl -Manifest $manifest   # for the Next-steps block (prefix-guarded)

    if ($DryRun) {
        Write-Log "[DryRun] WOULD download+verify Renew-Cert.ps1 $($manifest.renewal.version) and Create-New-Cert.ps1 $($manifest.creator.version)." -Level INFO
        if ($manifest.appProxySetup -and $manifest.appProxySetup.url) {
            Write-Log "[DryRun] WOULD also download+verify Setup-AppProxy.ps1 $($manifest.appProxySetup.version) (optional App Proxy setup tool)." -Level INFO
        }
        return
    }

    $thumb = Save-VerifiedDownload -Url $manifest.renewal.url -ExpectedSha256 $manifest.renewal.sha256 -TargetPath $RenewalScript -Label 'Renew-Cert.ps1'
    Write-Log "Placed Renew-Cert.ps1 $($manifest.renewal.version) (signer $thumb)." -Level SUCCESS

    try {
        $cthumb = Save-VerifiedDownload -Url $manifest.creator.url -ExpectedSha256 $manifest.creator.sha256 -TargetPath $CreatorScript -Label 'Create-New-Cert.ps1'
        Write-Log "Placed Create-New-Cert.ps1 $($manifest.creator.version) (signer $cthumb)." -Level SUCCESS
    }
    catch { Write-Log "Create-New-Cert.ps1 download failed: $($_.Exception.Message). Renewal is in place; re-run bootstrap to retry the creator." -Level WARNING }

    # Setup-AppProxy.ps1 (issue #64) - the optional, signed App Proxy setup tool. Best-effort and only when
    # the manifest carries it (older manifests won't): a fresh box can run it immediately if App Proxy is
    # needed; a box that never uses App Proxy simply has an unused (signed) script on disk.
    if ($manifest.appProxySetup -and $manifest.appProxySetup.url -and $manifest.appProxySetup.sha256) {
        try {
            $athumb = Save-VerifiedDownload -Url $manifest.appProxySetup.url -ExpectedSha256 $manifest.appProxySetup.sha256 -TargetPath $AppProxyScript -Label 'Setup-AppProxy.ps1'
            Write-Log "Placed Setup-AppProxy.ps1 $($manifest.appProxySetup.version) (signer $athumb)." -Level SUCCESS
        }
        catch { Write-Log "Setup-AppProxy.ps1 download failed: $($_.Exception.Message). It is optional; re-run bootstrap or fetch it later if App Proxy sync is needed." -Level WARNING }
    }

    Write-EventLogEntry $EID.ScriptsInstalled Information "Fleet scripts placed (renewal $($manifest.renewal.version), creator $($manifest.creator.version))"
}

function New-TelemetryBlock {
    # The cert-config Telemetry block (docs/telemetry-log-analytics-setup.md section6) - all non-secret.
    # The credential reference is platform-specific and the two forms are MUTUALLY EXCLUSIVE (issue #23
    # L1c): a thumbprint into LocalMachine\My on Windows, a PEM path on Linux. Only the one this platform
    # actually uses is emitted - carrying both with one null would put a permanent null key in every
    # Windows box's config, change its hash, and bill a config-change telemetry event for nothing.
    $block = [ordered]@{
        Enabled        = $true
        TenantId       = $DefaultSecretsTenantId
        AppClientId    = $TelemetryAppId
        DcrImmutableId = $TelemetryDcrImmutableId
        Stream         = $TelemetryStream
        EndpointUri    = $TelemetryEndpointUri
    }
    if ($IsWindowsHost) { $block['CertThumbprint'] = $TelemetrySpCertThumbprint }
    else                { $block['CertPath']       = (Get-PlatformPaths).KeyDir + '/telemetry-sp.pem' }
    return [pscustomobject]$block
}

function Set-TelemetryBlock {
    # Idempotent: add or refresh the Telemetry block on a config object (Duty 5).
    param([Parameter(Mandatory)][object] $Config)
    $Config | Add-Member -NotePropertyName 'Telemetry' -NotePropertyValue (New-TelemetryBlock) -Force
    return $Config
}

function Set-ScriptVersionStamps {
    # Bootstrap stamps BOTH versions from the freshly-placed scripts ON DISK - unlike the creator's
    # Set-ConfigVersionStamps, which stamps CreatorScriptVersion from its own $ScriptVersion (wrong here:
    # bootstrap's $ScriptVersion is the bootstrap version, not the creator's).
    param([Parameter(Mandatory)][object] $Config)
    $rv = Get-OnDiskScriptVersion -Path $RenewalScript
    $cv = Get-OnDiskScriptVersion -Path $CreatorScript
    if ($rv) { $Config | Add-Member -NotePropertyName 'RenewalScriptVersion' -NotePropertyValue $rv -Force }
    if ($cv) { $Config | Add-Member -NotePropertyName 'CreatorScriptVersion' -NotePropertyValue $cv -Force }
    return $Config
}

function New-FreshCertConfig {
    # The v2 skeleton for a fresh box (no existing config). No domains - the admin runs the creator to add
    # them. Mirrors the creator's New-DefaultCertConfig shape + the Telemetry block (Duty 5/6 fresh branch).
    $config = [pscustomobject]@{
        SchemaVersion        = 2
        RenewalScriptVersion = $null
        CreatorScriptVersion = $null
        SharedPoshAcmePath   = $SharedPoshAcmeDefault
        ManifestUrl          = $null
        PinVersion           = $null
        SecretsVault         = $null
        Billing              = $null
        Telemetry            = (New-TelemetryBlock)
        Domains              = @()
    }
    return (Set-ScriptVersionStamps -Config $config)
}

function ConvertTo-V2Config {
    # Duty 6 - map a v1 config object to the schema-v2 shape (pure; no I/O). v1 root is
    # {SharedPoshAcmePath, PaAccount, TeamsWebhookUrl, Domains}; each domain is
    # {MainDomain, Type, Guid, SANs, Thumbprint, NotAfter, +opt NetshIpPorts, RestartService} - all
    # byte-compatible with what the v2 renewal reads, so domains carry over verbatim. CARRY
    # SharedPoshAcmePath/PaAccount/Domains; DROP root TeamsWebhookUrl (now a vault secret in
    # cert-secrets.json); ADD SchemaVersion=2, version stamps, ManifestUrl/PinVersion/SecretsVault/
    # Billing=null, and the Telemetry block. Property order mirrors New-FreshCertConfig (+ PaAccount).
    param([Parameter(Mandatory)][object] $V1Config)
    $shared = if ($V1Config.SharedPoshAcmePath) { [string]$V1Config.SharedPoshAcmePath } else { $SharedPoshAcmeDefault }
    $config = [pscustomobject]@{
        SchemaVersion        = 2
        RenewalScriptVersion = $null
        CreatorScriptVersion = $null
        SharedPoshAcmePath   = $shared
        ManifestUrl          = $null
        PinVersion           = $null
        SecretsVault         = $null
        Billing              = $null
        Telemetry            = (New-TelemetryBlock)
        PaAccount            = $V1Config.PaAccount
        Domains              = @($V1Config.Domains)
    }
    return (Set-ScriptVersionStamps -Config $config)
}

function Invoke-V1Migration {
    # Windows-only by construction: v1 was a Windows-only product, so a Linux box is always a fresh v2
    # install and there is no v1 config, scheduled task or generated script to carry forward.
    # Duty 6 - migrate an existing v1 install. Backs up cert-config.json -> cert-config.json.pre-2.0.bak
    # (no secrets in it), converts to v2, and persists. The v1 GENERATED Renew-Cert.ps1 was already
    # replaced in place by Install-FleetScripts (Duty 4a runs BEFORE this) - deliberately NO cleartext
    # .bak of it (it embeds the hardcoded shared secrets). DryRun returns the converted object without
    # writing. Returns the v2 config object.
    param([Parameter(Mandatory)][object] $V1Config)
    $backupPath = "$ConfigPath.pre-2.0.bak"
    $domainCount = @($V1Config.Domains).Count

    if ($DryRun) {
        Write-Log "[DryRun] WOULD back up cert-config.json -> $backupPath and migrate to v2 (carry $domainCount domain(s) + PaAccount '$($V1Config.PaAccount)' + SharedPoshAcmePath; drop root TeamsWebhookUrl - now a vault secret; add SchemaVersion=2, version stamps, Telemetry block)." -Level INFO
        return (ConvertTo-V2Config -V1Config $V1Config)
    }

    try {
        Copy-Item -Path $ConfigPath -Destination $backupPath -Force
        Write-Log "Backed up v1 cert-config.json -> $backupPath" -Level SUCCESS
    }
    catch { Write-Log "Could not back up cert-config.json to ${backupPath}: $($_.Exception.Message). Continuing with the migration." -Level WARNING }

    if ($V1Config.PSObject.Properties['TeamsWebhookUrl'] -and $V1Config.TeamsWebhookUrl) {
        Write-Log '  Dropping root TeamsWebhookUrl from config (v2 reads it from cert-secrets.json, synced from the vault).' -Level INFO
    }

    $config = ConvertTo-V2Config -V1Config $V1Config
    Write-Log "Migrated config to v2: carried $domainCount domain(s)$(if ($config.PaAccount) { " + PaAccount $($config.PaAccount)" }), SharedPoshAcmePath=$($config.SharedPoshAcmePath). The v1 generated Renew-Cert.ps1 was replaced by the signed v2 download (no backup - it held hardcoded secrets)." -Level SUCCESS
    $null = Save-CertConfig -Config $config -Reason 'v1->v2 migration'
    Write-EventLogEntry $EID.Migrated Information "Migrated cert-config v1 -> v2 ($domainCount domains)"
    Send-Telemetry -Config $config -Outcome ([pscustomobject]@{ Action = 'migrate'; RunOutcome = "Migrated ($domainCount domains)" })
    return $config
}

function Initialize-CertConfig {
    # Duties 5 + 6. Write/update cert-config.json: migrate v1, top-up an existing v2, or write a fresh
    # skeleton. Every branch ensures the Telemetry block + version stamps. Returns the config object.
    $existing = if (Test-Path $ConfigPath) { Get-CertConfig } else { $null }

    if (-not $existing) {
        Write-Log 'No existing cert-config.json - writing a fresh v2 skeleton.' -Level INFO
        $config = New-FreshCertConfig
        $null = Save-CertConfig -Config $config -Reason 'fresh v2 config'
        return $config
    }

    $schema = if ($existing.PSObject.Properties['SchemaVersion']) { [int]$existing.SchemaVersion } else { 0 }
    if ($schema -ne 2) {
        Write-Log "Existing cert-config.json is v1 (SchemaVersion=$schema). Migrating to v2..." -Level WARNING
        return (Invoke-V1Migration -V1Config $existing)   # PR B
    }

    Write-Log 'Existing cert-config.json is already v2 - topping up Telemetry block + version stamps.' -Level INFO
    $config = Set-TelemetryBlock -Config $existing
    $config = Set-ScriptVersionStamps -Config $config
    $null = Save-CertConfig -Config $config -Reason 'v2 top-up (Telemetry + stamps)'
    return $config
}

function Sync-BootstrapSecrets {
    # Pull the 4 shared secrets from the vault (SP-cert auth) into cert-secrets.json. BEST-EFFORT
    # (Decision Q1): on failure, warn + continue - the box is configured; the next creator run (before
    # issuance) and the daily renewal refresh (D2) heal cert-secrets.json. A transient Azure hiccup must
    # not fail an otherwise-complete bootstrap.
    param([object] $Config)
    $vaultName = Get-ResolvedVaultName -Config $Config
    try {
        $null = Sync-SecretsFromVault -VaultName $vaultName
        Send-Telemetry -Config $Config -Outcome ([pscustomobject]@{ Action = 'bootstrap-secrets'; RunOutcome = 'Synced' })
    }
    catch {
        Write-Log "Vault secrets sync failed: $($_.Exception.Message). Continuing - the box is configured; the next creator run (before issuance) and the daily renewal refresh will heal cert-secrets.json." -Level WARNING
        Write-EventLogEntry $EID.Start Warning "Bootstrap vault secrets sync failed (best-effort): $($_.Exception.Message)"
    }
}

function Write-BootstrapNextSteps {
    # Bootstrap-only (#86). Tell the operator what to do now, tailored to the box: no managed certificates ->
    # run the creator; certificates present (migrated / re-run) -> verify. Ends with the operations guide URL
    # (Resolve-GuideUrl) and, on an interactive non-DryRun run, offers to open it in the default browser.
    # Best-effort: a hiccup here must never turn a completed bootstrap into an error.
    param([object] $Config)
    try {
        $domains = @(); if ($Config -and $Config.Domains) { $domains = @($Config.Domains) }
        Write-Log '--- Next steps ---' -Level INFO
        if ($domains.Count -eq 0) {
            Write-Log "1. Add your certificates (elevated):  & '$CreatorScript'" -Level INFO
            Write-Log '   Have the _acme-challenge CNAME for each name in place first; the creator prints the exact record if it is missing.' -Level INFO
            Write-Log "2. Verify:  & '$CreatorScript' -CheckOnly    and    & '$RenewalScript' -DryRun" -Level INFO
        }
        else {
            Write-Log "This server manages $($domains.Count) certificate(s). Verify they are all listed and the daily run is clean:" -Level INFO
            Write-Log "   & '$CreatorScript' -CheckOnly" -Level INFO
            Write-Log "   & '$RenewalScript' -DryRun" -Level INFO
            Write-Log "   Get-ScheduledTask -TaskName '$RenewalTaskName'" -Level INFO
        }
        Write-Log "Step-by-step guide (install, upgrade, day-2, troubleshooting): $($script:GuideUrl)" -Level INFO
        if ($DryRun -or -not (Test-HostInteractive)) { return }
        $answer = ([string](Read-Host 'Open the guide in your browser now? [y/N]')).Trim()
        if ($answer -match '^[Yy]') {
            Start-Process $script:GuideUrl | Out-Null
            Write-Log 'Opened the guide in the default browser.' -Level INFO
        }
    }
    catch { Write-Log "Could not print next steps: $($_.Exception.Message)" -Level DEBUG }
}

