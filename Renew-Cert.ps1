        $root = 'C:\Cert\Renewal'
        return [pscustomobject]@{
            ScriptsDir      = $root
            ConfigDir       = $root
            StateDir        = $root
            # Literal concatenation, not Join-Path: Join-Path resolves against the running host's
            # providers, so a 'C:\...' base THROWS on Linux ("A drive with the name 'C' does not exist").
